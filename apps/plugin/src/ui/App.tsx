import React, { useEffect, useMemo, useState } from "react";

declare const parent: {
  postMessage: (message: unknown, target: string) => void;
};

type Token = {
  id: string;
  name: string;
  type: string;
  collectionName: string;
  modes: {
    modeId: string;
    modeName: string;
    value: unknown;
    aliasTo?: string;
  }[];
};

type ScanResult = {
  fileName: string;
  collections: {
    id: string;
    name: string;
    modes: { modeId: string; name: string }[];
  }[];
  tokens: Token[];
};

function send(type: string) {
  parent.postMessage({
    pluginMessage: { type }
  }, "*");
}

function toKebabCase(value: string) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[\\s_/]+/g, "-")
    .replace(/[^a-zA-Z0-9-]/g, "")
    .toLowerCase();
}

function colorToCss(value: any): string {
  if (!value || typeof value !== "object") return String(value);

  const r = Math.round((value.r ?? 0) * 255);
  const g = Math.round((value.g ?? 0) * 255);
  const b = Math.round((value.b ?? 0) * 255);
  const a = value.a ?? 1;

  if (a >= 1) {
    return "#" + [r, g, b]
      .map(x => x.toString(16).padStart(2, "0"))
      .join("");
  }

  return `rgba(${r}, ${g}, ${b}, ${a})`;
}

function exportCss(data: ScanResult): string {
  const lines = [
    "/* Generated by Design Token - Code Sync */",
    ":root {"
  ];

  for (const token of data.tokens) {
    const value = token.modes[0]?.value;

    let output = value;

    if (token.type === "COLOR") {
      output = colorToCss(value);
    }

    if (token.type === "FLOAT" && typeof value === "number") {
      output = `${value}px`;
    }

    if (token.type === "STRING") {
      output = JSON.stringify(value ?? "");
    }

    if (token.type === "BOOLEAN") {
      output = String(value);
    }

    lines.push(
      `  --${toKebabCase(token.name)}: ${output};`
    );
  }

  lines.push("}");

  return lines.join("\n");
}

export default function App() {
  const [data, setData] = useState<ScanResult | null>(null);
  const [loading, setLoading] = useState(false);
  const [search, setSearch] = useState("");
  const [status, setStatus] = useState("Ready to scan your Figma file.");

  useEffect(() => {
    function handleMessage(event: MessageEvent) {
      const message = event.data?.pluginMessage;

      if (!message) return;

      if (message.type === "SCAN_RESULT") {
        setData(message.payload);
        setLoading(false);

        setStatus(
          `Successfully scanned ${message.payload.tokens.length} variables.`
        );
      }

      if (message.type === "ERROR") {
        setLoading(false);
        setStatus(message.message);
      }
    }

    window.addEventListener("message", handleMessage);

    return () => {
      window.removeEventListener("message", handleMessage);
    };
  }, []);

  const filteredTokens = useMemo(() => {
    if (!data) return [];

    return data.tokens.filter(token =>
      token.name.toLowerCase().includes(search.toLowerCase())
    );
  }, [data, search]);

  function downloadCss() {
    if (!data) return;

    const css = exportCss(data);
    const blob = new Blob([css], {
      type: "text/css;charset=utf-8"
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    link.href = url;
    link.download = "design-tokens.css";
    link.click();

    URL.revokeObjectURL(url);
  }

  return (
    <main className="app">

      <header className="header">
        <div className="logo">T</div>

        <div>
          <h2>Token Sync</h2>
          <p>Design Token → Code Sync</p>
        </div>

        <span className="badge">BETA</span>
      </header>

      <section className="hero">
        <span className="eyebrow">FIGMA VARIABLE EXPORTER</span>

        <h1>
          Design tokens,
          <br />
          <span>ready for code.</span>
        </h1>

        <p>
          Extract your design variables and
          generate developer-ready code.
        </p>

        <button
          className="primary"
          disabled={loading}
          onClick={() => {
            setLoading(true);
            setStatus("Scanning variables...");
            send("SCAN");
          }}
        >
          {loading ? "Scanning..." : "↻ Scan Figma Variables"}
        </button>

        <div className="status">{status}</div>
      </section>

      {data && (
        <>
          <section className="stats">
            <div>
              <strong>{data.tokens.length}</strong>
              <span>Variables</span>
            </div>

            <div>
              <strong>{data.collections.length}</strong>
              <span>Collections</span>
            </div>

            <div>
              <strong>
                {data.collections.reduce(
                  (total, collection) =>
                    total + collection.modes.length,
                  0
                )}
              </strong>
              <span>Modes</span>
            </div>
          </section>

          <section className="panel">
            <div className="panel-heading">
              <h3>Design Variables</h3>
              <span>{filteredTokens.length} tokens</span>
            </div>

            <input
              placeholder="Search variables..."
              value={search}
              onChange={event => setSearch(event.target.value)}
            />

            <div className="token-list">
              {filteredTokens.map(token => (
                <div className="token-row" key={token.id}>
                  <span className={`dot ${token.type.toLowerCase()}`} />

                  <div className="token-info">
                    <strong>{token.name}</strong>
                    <small>{token.collectionName}</small>
                  </div>

                  <span className="token-type">{token.type}</span>
                </div>
              ))}

              {filteredTokens.length === 0 && (
                <p className="empty">No variables found.</p>
              )}
            </div>
          </section>

          <section className="panel">
            <div className="panel-heading">
              <h3>Export code</h3>
              <span>CSS</span>
            </div>

            <pre className="code">
              {exportCss(data).slice(0, 3000)}
            </pre>

            <button
              className="primary"
              onClick={downloadCss}
            >
              ↓ Export CSS
            </button>
          </section>
        </>
      )}

      <footer>
        Design Token → Code Sync · Local export
      </footer>

    </main>
  );
}
